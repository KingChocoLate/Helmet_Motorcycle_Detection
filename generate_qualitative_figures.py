def font(size):
    for path in FONTS:
        if Path(path).is_file():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as fp:
        for chunk in iter(lambda: fp.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def dataset_dir(root, specified=None):
    """Find an existing annotated Cambodian test split without duplicating datasets."""
    candidates = []
    if specified:
        d = Path(specified).expanduser().resolve()
        candidates = [d, d / 'test']
    else:
        project = PROJECT_ROOT
        for base in (project, ROOT):
            candidates.extend([
                base / 'cambodian_helmet_dataset_v1i_bbox_format_fixed' / 'test',
                base / 'cambodian_helmet_dataset_v1i_bbox_format_fixed',
                base / 'dataset' / 'test',
                base / 'test',
            ])
            # Other common Roboflow dataset names (limited to directory names).
            for child in sorted(base.glob('cambodian_helmet_dataset*')):
                if child.is_dir():
                    candidates.extend([child / 'test', child])
    # Accept only the intended dataset: the exact four selected filenames AND labels.
    for candidate in candidates:
        imgdir, labdir = candidate / 'images', candidate / 'labels'
        if not (imgdir.is_dir() and labdir.is_dir()):
            continue
        if all((imgdir / name).is_file() and (labdir / (Path(name).stem+'.txt')).is_file()
               for _, name, _ in SCENES):
            return candidate
    examples = '\n'.join(' - ' + str(d) for d in candidates[:12])
    raise FileNotFoundError(
        'Cannot find the Cambodian test split containing all four selected scenes.\n'
        'Its directory must contain images/ and labels/.\nChecked:\n' + examples +
        '\nPass --dataset /full/path/to/your/test to select it explicitly.'
    )


def find_models(custom, overrides):
    """Prefer the original trained checkpoints already in src/runs or parent/runs."""
    files={}
    for model, shortname in MODELS:
        if overrides.get(model):
            path = Path(overrides[model]).expanduser().resolve()
            candidates = [path]
        elif custom:
            candidates = [Path(custom).expanduser().resolve() / shortname]
        else:
            candidates = [
                ROOT / 'runs' / TRAINING_RUNS[model],
                PROJECT_ROOT / 'runs' / TRAINING_RUNS[model],
                ROOT / 'models' / shortname,
                PROJECT_ROOT / 'models' / shortname,
            ]
        found = next((p for p in candidates if p.is_file()), None)
        if not found:
            raise FileNotFoundError(
                f'Missing checkpoint for {model}. Checked:\n' +
                '\n'.join(' - '+str(p) for p in candidates) +
                '\nUse --models-dir with four renamed weights or an individual --*-weights argument.'
            )
        files[model]=found
    return files


def truth(image_path, label_dir):
    image_width, image_height = Image.open(image_path).size
    label_path = label_dir / (image_path.stem + '.txt')
    if not label_path.is_file():
        raise FileNotFoundError(f'Ground-truth label missing: {label_path}')
    boxes = []
    for line_number, raw in enumerate(label_path.read_text(encoding='utf-8').splitlines(), start=1):
        if not raw.strip():
            continue
        p = raw.split()
        if len(p) != 5:
            raise ValueError(f'{label_path}:{line_number}: expected 5 YOLO columns, got {len(p)}')
        cls = int(p[0])
        cx, cy, w, h = map(float, p[1:])
        if cls not in (0, 1, 2) or w <= 0 or h <= 0:
            raise ValueError(f'{label_path}:{line_number}: invalid class/box')
        boxes.append({'class': cls, 'xyxy': [max(0, (cx-w/2)*image_width), max(0, (cy-h/2)*image_height),
                                                min(image_width, (cx+w/2)*image_width), min(image_height, (cy+h/2)*image_height)],
                      'conf': 1.0})
    return boxes


def predict(model_path, image_paths, imgsz, conf, iou, device):
    from ultralytics import YOLO
    model = YOLO(str(model_path))
    names = model.names
    actual = [str(names[i] if not isinstance(names, dict) else names.get(i, '')) for i in range(3)]
    if [n.casefold().replace('_','') for n in actual] != [n.casefold() for n in CLASSES]:
        raise ValueError(f'{model_path.name}: unexpected class order {actual}; expected {CLASSES}.')
    predictions = {}
    for image_path in image_paths:
        result = model.predict(source=str(image_path), imgsz=imgsz, conf=conf, iou=iou,
                               device=device, verbose=False, save=False)[0]
        arr = []
        if result.boxes is not None:
            for bb, c, score in zip(result.boxes.xyxy.cpu().tolist(),
                                    result.boxes.cls.cpu().tolist(), result.boxes.conf.cpu().tolist()):
                c = int(c)
                if c in (0,1,2):
                    arr.append({'class': c, 'xyxy': [float(v) for v in bb], 'conf': float(score)})
        predictions[image_path.name] = arr
    return predictions


def draw_panel(image_path, boxes, max_side=940):
    image = Image.open(image_path).convert('RGB')
    scale = min(1, max_side / max(image.size))
    if scale < 1:
        image = image.resize((round(image.width*scale),round(image.height*scale)), Image.Resampling.LANCZOS)
    d = ImageDraw.Draw(image)
    # Draw every box. Never hide boxes by truncating the GT or predictions to a limit.
    for rec in sorted(boxes, key=lambda p: -(p['xyxy'][2]-p['xyxy'][0])*(p['xyxy'][3]-p['xyxy'][1])):
        xy = [int(round(v * scale)) for v in rec['xyxy']]
        if xy[2] > xy[0] and xy[3] > xy[1]:
            d.rectangle(xy, outline=COLORS[rec['class']], width=2)
    return image


def draw_comparison(image_path, gt, by_model, out_path):
    width, height = 1800, 1820
    canvas = Image.new('RGB', (width, height), 'white')
    d = ImageDraw.Draw(canvas)
    titles = ['(a) Ground truth', '(b) Indian baseline', '(c) Indian weighted',
              '(d) Cambodian adapted v1', '(e) Cambodian adapted v2']
    images = [gt] + [by_model[model][image_path.name] for model, _ in MODELS]
    # GT top/center; model results 2x2 below.
    pos = [(450, 12), (35, 602), (925, 602), (35, 1195), (925, 1195)]
    for title, records, (x, y) in zip(titles, images, pos):
        d.text((x+8, y+6), title, fill='#172633', font=font(27))
        im = draw_panel(image_path, records)
        im.thumbnail((820, 500), Image.Resampling.LANCZOS)
        image_x = x+(830-im.width)//2
        image_y = y+45+(505-im.height)//2
        canvas.paste(im,(image_x,image_y))
        d.rectangle((image_x, image_y, image_x+im.width, image_y+im.height), outline='#C5CED8', width=2)
    x = 435
    for idx, cls in enumerate(CLASSES):
        d.rectangle((x, 1780, x+25, 1805), outline=COLORS[idx], width=4)
        d.text((x+37, 1779), cls, font=font(23), fill='#172633')
        x += [338,235,245][idx]
    canvas.save(out_path, optimize=True)


def box_iou(a,b):
    x0,y0,x1,y1=max(a[0],b[0]), max(a[1],b[1]), min(a[2],b[2]), min(a[3],b[3])
    intersection=max(0,x1-x0)*max(0,y1-y0)
    a_area=max(0,a[2]-a[0])*max(0,a[3]-a[1]);b_area=max(0,b[2]-b[0])*max(0,b[3]-b[1])
    return intersection/max(1.e-8,a_area+b_area-intersection)


def simple_counts(pred, gt):
    # Descriptive TP/FP/FN at conf cutoff and IoU 0.5. Not mAP.
    result={}
    for class_id, class_name in enumerate(CLASSES):
        ps=sorted((p for p in pred if p['class']==class_id),key=lambda p:-p['conf'])
        gs=[g for g in gt if g['class']==class_id]
        used=set(); tp=0
        for p in ps:
            candidates=[(box_iou(p['xyxy'],g['xyxy']),j) for j,g in enumerate(gs) if j not in used]
            if candidates:
                i,j=max(candidates)
                if i>=0.5:
                    used.add(j);tp+=1
        result[class_name]={'ground_truth':len(gs),'true_positives':tp,'false_positives':len(ps)-tp,'missed_gt':len(gs)-tp}
    return result


